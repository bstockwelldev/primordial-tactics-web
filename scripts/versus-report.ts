// Versus balance harness (docs/local-versus-spec.md): first-mover win rate in mirrored matches and each
// template's win rate across random drafts, from the headless simulator.
// Usage: npx tsx scripts/versus-report.ts [drafts=400] > versus-report.md
// The bots are proxies for people: use this to find clearly broken templates and the size of the
// move-order bias, not to hit exact targets.

import { BOT_PROFILES as P } from '../src/game/bot';
import { buildArenaGrid } from '../src/game/arenaSetup';
import { createRng } from '../src/game/rng';
import { simulateMatch } from '../src/game/sim';
import { VERSUS_TEMPLATE_IDS, buildVersusUnits, randomSquad } from '../src/game/versus';

const DRAFTS = Number(process.argv[2] ?? 400);
const grid = buildArenaGrid();

/** 95% Wilson interval, as percentages. */
function wilson(wins: number, n: number): [number, number] {
  const z = 1.96;
  const p = wins / n;
  const d = 1 + (z * z) / n;
  const centre = (p + (z * z) / (2 * n)) / d;
  const half = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [Math.max(0, centre - half) * 100, Math.min(1, centre + half) * 100];
}
const fmt = (wins: number, n: number) => {
  const [lo, hi] = wilson(wins, n);
  return `${((wins / n) * 100).toFixed(0)}% (${lo.toFixed(0)}–${hi.toFixed(0)})`;
};

const out: string[] = ['# Versus balance report', ''];
out.push(`Generated by \`npx tsx scripts/versus-report.ts ${DRAFTS}\`. Moderate bots on both sides; side A always moves first. Cells show win rate with a 95% Wilson interval.`);
out.push('');

// 1. Random drafts: each side picks 3 distinct templates uniformly. Every template's win rate is taken over
// the squads that contain it (a squad wins when its side wins; draws count as half a win).
const rng = createRng(12345);
const stat: Record<string, { wins: number; n: number }> = {};
for (const id of VERSUS_TEMPLATE_IDS) stat[id] = { wins: 0, n: 0 };
let aWins = 0;
let draws = 0;
for (let i = 0; i < DRAFTS; i++) {
  const a = randomSquad(rng);
  const b = randomSquad(rng);
  const r = simulateMatch({ units: buildVersusUnits(a, b), grid, seed: i + 1, player: P.moderate, enemy: P.moderate });
  const score = r.winner === 'player' ? [1, 0] : r.winner === 'enemy' ? [0, 1] : [0.5, 0.5];
  if (r.winner === 'player') aWins++;
  if (r.winner === 'draw') draws++;
  for (const id of a) {
    stat[id].wins += score[0];
    stat[id].n++;
  }
  for (const id of b) {
    stat[id].wins += score[1];
    stat[id].n++;
  }
}
out.push('## Move order (random drafts)');
out.push('');
out.push('Side A moves first. 50% means no edge.');
out.push('');
out.push('| Drafts | Side A (first mover) wins | Draws |');
out.push('|---|---|---|');
out.push(`| ${DRAFTS} | ${fmt(aWins, DRAFTS)} | ${draws} |`);
out.push('');

// 2. Mirrored matches: the same squad on both sides, so any gap is purely move order.
out.push('## Mirrored squads (same three units both sides)');
out.push('');
out.push('| Squad | First mover wins |');
out.push('|---|---|');
const squads = [
  ['velociraptor', 'triceratops', 'commander'],
  ['pteranodon', 'ankylosaurus', 'dilophosaurus'],
  ['velociraptor', 'pteranodon', 'dilophosaurus'],
  ['triceratops', 'ankylosaurus', 'commander'],
];
const SEEDS = Math.max(40, Math.floor(DRAFTS / 4));
for (const s of squads) {
  let w = 0;
  for (let seed = 1; seed <= SEEDS; seed++) {
    if (simulateMatch({ units: buildVersusUnits(s, s), grid, seed, player: P.moderate, enemy: P.moderate }).winner === 'player') w++;
  }
  out.push(`| ${s.join(', ')} | ${fmt(w, SEEDS)} |`);
}
out.push('');

out.push('## Template win rates (random drafts)');
out.push('');
out.push('Share of matches won by squads that contain the template. Target after tuning: 45-55%.');
out.push('');
out.push('| Template | Appearances | Win rate |');
out.push('|---|---|---|');
for (const id of VERSUS_TEMPLATE_IDS) out.push(`| ${id} | ${stat[id].n} | ${fmt(stat[id].wins, stat[id].n)} |`);
out.push('');

console.log(out.join('\n'));
