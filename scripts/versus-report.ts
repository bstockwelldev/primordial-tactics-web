// Versus balance report (docs/local-versus-spec.md): move-order bias, and template and squad win rates
// across random drafts, from the headless simulator. The shipped fairness answer is a best of two with
// sides swapped, so the template numbers are pair results.
// Usage: npx tsx scripts/versus-report.ts [pairs=600] > docs/balance-versus.md
// The bots are proxies for people: use this to find clearly broken templates and the size of the
// move-order bias, not to hit exact targets.

import { BOT_PROFILES as P } from '../src/game/bot';
import { buildArenaGrid } from '../src/game/arenaSetup';
import { VERSUS_TEMPLATE_SCALE } from '../src/game/balance';
import { createRng } from '../src/game/rng';
import { simulateMatch, simulatePair } from '../src/game/sim';
import { VERSUS_TEMPLATE_IDS, buildVersusUnits, randomSquad } from '../src/game/versus';

const PAIRS = Number(process.argv[2] ?? 600);
const grid = buildArenaGrid();

/** 95% Wilson interval, as percentages. */
function wilson(wins: number, n: number): [number, number] {
  const z = 1.96;
  const p = wins / n;
  const d = 1 + (z * z) / n;
  const centre = (p + (z * z) / (2 * n)) / d;
  const half = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [Math.max(0, centre - half) * 100, Math.min(1, centre + half) * 100];
}
const fmt = (wins: number, n: number) => {
  const [lo, hi] = wilson(wins, n);
  return `${((wins / n) * 100).toFixed(0)}% (${lo.toFixed(0)}–${hi.toFixed(0)})`;
};

const out: string[] = ['# Versus balance (local pass & play, best of two)', ''];
out.push(
  `Generated by \`npx tsx scripts/versus-report.ts ${PAIRS}\`. Moderate bots on both sides, level-5 templates with the tuned multipliers in \`VERSUS_TEMPLATE_SCALE\`. Cells show win rate with a 95% Wilson interval; a draw counts as half a win.`
);
out.push('');

// 1. Move-order bias: every possible squad against itself, single game, side A moves first.
const ids = [...VERSUS_TEMPLATE_IDS];
const squads: string[][] = [];
for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) for (let k = j + 1; k < ids.length; k++) squads.push([ids[i], ids[j], ids[k]]);
const SEEDS = 40;
const firstMover: number[] = [];
for (const s of squads) {
  let w = 0;
  for (let seed = 1; seed <= SEEDS; seed++) {
    if (simulateMatch({ units: buildVersusUnits(s, s), grid, seed, player: P.moderate, enemy: P.moderate }).winner === 'player') w++;
  }
  firstMover.push((w / SEEDS) * 100);
}
const mean = firstMover.reduce((a, b) => a + b, 0) / firstMover.length;
const dev = firstMover.reduce((a, b) => a + Math.abs(b - 50), 0) / firstMover.length;
out.push('### Move order');
out.push('');
out.push(
  'A single game has a large move-order bias that depends on the squads and runs both ways: the same squad on both sides, first mover win rate, over all 20 possible squads:'
);
out.push('');
out.push(`\`${firstMover.map((x) => x.toFixed(0)).join(' ')}\` — mean ${mean.toFixed(0)}%, mean distance from 50% ${dev.toFixed(0)} points (min ${Math.min(...firstMover).toFixed(0)}%, max ${Math.max(...firstMover).toFixed(0)}%).`);
out.push('');
out.push(
  'No single compensation knob fixes a bias that runs both ways (a round-1 AP bonus of -1, +1 and +2 left the average distance at 28, 20 and 26 points), so a match is a best of two with sides swapped: each player moves first once. For two identical squads the order effect then cancels apart from the dice.'
);
out.push('');

// 2. Template win rates across random draft pairs (best of two each).
const rng = createRng(424242);
const stat: Record<string, { w: number; n: number }> = {};
for (const id of VERSUS_TEMPLATE_IDS) stat[id] = { w: 0, n: 0 };
let decided = 0;
for (let i = 0; i < PAIRS; i++) {
  const a = randomSquad(rng);
  const b = randomSquad(rng);
  const r = simulatePair({ picksA: a, picksB: b, grid, seed: 100000 + i, a: P.moderate, b: P.moderate });
  const sa = r.winner === 'a' ? 1 : r.winner === 'draw' ? 0.5 : 0;
  if (r.winner !== 'draw') decided++;
  for (const id of a) {
    stat[id].w += sa;
    stat[id].n++;
  }
  for (const id of b) {
    stat[id].w += 1 - sa;
    stat[id].n++;
  }
}
out.push('### Template win rates');
out.push('');
out.push(`${PAIRS} random draft pairs (each side picks 3 distinct templates); a template's rate is over the squads that contain it. Target: 45-55%. Pairs with a clear winner: ${decided} of ${PAIRS}.`);
out.push('');
out.push('| Template | Multiplier (hp and attack) | Appearances | Win rate | In 45-55% |');
out.push('|---|---|---|---|---|');
let outOfBand = 0;
for (const id of VERSUS_TEMPLATE_IDS) {
  const pct = (stat[id].w / stat[id].n) * 100;
  const ok = pct >= 45 && pct <= 55;
  if (!ok) outOfBand++;
  out.push(`| ${id} | x${VERSUS_TEMPLATE_SCALE[id]?.hp ?? 1} | ${stat[id].n} | ${fmt(stat[id].w, stat[id].n)} | ${ok ? 'yes' : 'NO'} |`);
}
out.push('');
out.push(outOfBand === 0 ? 'Every template is inside the band.' : `${outOfBand} template(s) are outside the band: re-tune their multiplier.`);
out.push('');

// 3. Squad combinations: every squad against every other (best of two). Catches a dominant or useless combination.
const squadRate: Array<{ squad: string; rate: number }> = squads.map((s) => ({ squad: s.join(', '), rate: 0 }));
const games = squads.map(() => 0);
for (let i = 0; i < squads.length; i++) {
  for (let j = i + 1; j < squads.length; j++) {
    const r = simulatePair({ picksA: squads[i], picksB: squads[j], grid, seed: 500000 + i * 100 + j, a: P.moderate, b: P.moderate });
    const sa = r.winner === 'a' ? 1 : r.winner === 'draw' ? 0.5 : 0;
    squadRate[i].rate += sa;
    squadRate[j].rate += 1 - sa;
    games[i]++;
    games[j]++;
  }
}
squadRate.forEach((s, i) => (s.rate = (s.rate / games[i]) * 100));
squadRate.sort((a, b) => b.rate - a.rate);
out.push('### Squad combinations');
out.push('');
out.push('Each of the 20 possible squads against every other squad (best of two, 19 opponents each). Even would be 50% for all; the spread shows how much the combination matters.');
out.push('');
out.push('| Squad | Win rate |');
out.push('|---|---|');
for (const s of [...squadRate.slice(0, 3), ...squadRate.slice(-3)]) out.push(`| ${s.squad} | ${s.rate.toFixed(0)}% |`);
out.push('');
out.push(`Best ${squadRate[0].rate.toFixed(0)}%, worst ${squadRate[squadRate.length - 1].rate.toFixed(0)}%.`);
out.push('');

console.log(out.join('\n'));
