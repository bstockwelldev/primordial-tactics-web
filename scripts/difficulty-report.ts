// Difficulty report: win rates by sector, bot skill and move order, from the headless simulator.
// Usage: npx tsx scripts/difficulty-report.ts [seeds=200] > docs/balance.md
// The bots are proxies, not people: use this to find clearly broken cells, not to hit exact targets.

import { BOT_PROFILES as P, BotProfile } from '../src/game/bot';
import { buildArenaGrid, buildSoloUnits } from '../src/game/arenaSetup';
import { ISLAND_CAMPAIGN_SECTORS } from '../src/game/constants';
import { simulateMatch } from '../src/game/sim';
import { TamedDino, UnitEntity } from '../src/types/game';

const SEEDS = Number(process.argv[2] ?? 200);
const grid = buildArenaGrid();

const starters: TamedDino[] = [
  { instanceId: 'a', speciesId: 'velociraptor', customName: 'Ghostclaw', level: 5, xp: 0, currentHp: 160, maxHp: 160, currentTorpor: 0, maxTorpor: 120, attack: 48, defense: 16, speed: 4, equippedAbilities: [] },
  { instanceId: 'b', speciesId: 'triceratops', customName: 'Shieldhorn', level: 4, xp: 0, currentHp: 290, maxHp: 290, currentTorpor: 0, maxTorpor: 260, attack: 34, defense: 38, speed: 2, equippedAbilities: [] },
];

interface Cell {
  wins: number;
  n: number;
  unfinished: number;
  rounds: number;
}

/** Player-side win rate of `skill` (player) against a moderate enemy, over SEEDS seeds. */
function run(units: UnitEntity[], player: BotProfile): Cell {
  const c: Cell = { wins: 0, n: SEEDS, unfinished: 0, rounds: 0 };
  for (let seed = 1; seed <= SEEDS; seed++) {
    const r = simulateMatch({ units, grid, seed, player, enemy: P.moderate });
    if (r.winner === 'player') c.wins++;
    if (r.winner === 'unfinished') c.unfinished++;
    c.rounds += r.rounds;
  }
  return c;
}

/** 95% Wilson interval, as percentages. */
function wilson(wins: number, n: number): [number, number] {
  const z = 1.96;
  const p = wins / n;
  const d = 1 + (z * z) / n;
  const centre = (p + (z * z) / (2 * n)) / d;
  const half = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [Math.max(0, centre - half) * 100, Math.min(1, centre + half) * 100];
}

function fmt(c: Cell): string {
  const [lo, hi] = wilson(c.wins, c.n);
  return `${((c.wins / c.n) * 100).toFixed(0)}% (${lo.toFixed(0)}–${hi.toFixed(0)})`;
}

const out: string[] = [];
out.push('# Difficulty report');
out.push('');
out.push(`Generated by \`npx tsx scripts/difficulty-report.ts ${SEEDS}\`. ${SEEDS} seeds per cell; cells show win rate with a 95% Wilson interval.`);
out.push('Player squad: commander + Ghostclaw (L5 raptor) + Shieldhorn (L4 trike), the test starter squad. Enemy pilot: moderate bot. Player always moves first.');
out.push('The bots are proxies for people, not people. Treat gaps as signals to investigate, not targets to hit.');
out.push('');

out.push('## Campaign sectors: starter squad vs the sector squad');
out.push('');
out.push('| Sector | Threat | Enemies | Moderate player | Easy player | Avg rounds (moderate) | Unfinished |');
out.push('|---|---|---|---|---|---|---|');
for (const s of ISLAND_CAMPAIGN_SECTORS) {
  const units = buildSoloUnits('Tester', starters, s as never);
  const mod = run(units, P.moderate);
  const easy = run(units, P.easy);
  const enemies = s.enemySquad.map((e) => `${e.name} L${e.level}`).join(', ');
  out.push(`| ${s.id} | ${s.threatLevel} | ${enemies} | ${fmt(mod)} | ${fmt(easy)} | ${(mod.rounds / mod.n).toFixed(1)} | ${mod.unfinished + easy.unfinished} |`);
}

const sk = run(buildSoloUnits('Tester', starters, null), P.moderate);
const skEasy = run(buildSoloUnits('Tester', starters, null), P.easy);
out.push('');
out.push('## Skirmish (default rival squad)');
out.push('');
out.push('| Moderate player | Easy player | Avg rounds (moderate) | Unfinished |');
out.push('|---|---|---|---|');
out.push(`| ${fmt(sk)} | ${fmt(skEasy)} | ${(sk.rounds / sk.n).toFixed(1)} | ${sk.unfinished + skEasy.unfinished} |`);

// Move-order edge: a perfectly mirrored match, moderate vs moderate. 50% means no edge.
const squad = buildSoloUnits('Tester', starters, null).filter((u) => u.isPlayer);
const mirrored: UnitEntity[] = [
  ...squad,
  ...squad.map((u) => ({ ...u, id: `m_${u.id}`, isPlayer: false, ownerId: 'ai_bot', x: 7 - u.x, y: 5 - u.y })),
];
const mirror = run(mirrored, P.moderate);
out.push('');
out.push('## Move-order edge (mirrored squads, moderate vs moderate)');
out.push('');
out.push('First mover win rate; 50% means no edge.');
out.push('');
out.push(`| First mover wins |`);
out.push('|---|');
out.push(`| ${fmt(mirror)} |`);
out.push('');

console.log(out.join('\n'));
